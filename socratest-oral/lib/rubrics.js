// 텍스트 줄 → 기준 객체 배열
export function parseRubric(lines) {
  const arr = (Array.isArray(lines) ? lines : String(lines || '').split('\n'))
    .map((l) => String(l).trim())
    .filter(Boolean)
    .map((l) => {
      const [name, points, desc = '', who = ''] = l.split('|').map((x) => x.trim());
      return { name: name.slice(0, 40), points: Math.round(Number(points)), desc: desc.slice(0, 400), teacherOnly: /교사/.test(who) };
    })
    .filter((c) => c.name && Number.isFinite(c.points) && c.points > 0 && c.points <= 100);
  const names = new Set();
  return arr.filter((c) => !names.has(c.name) && names.add(c.name)).slice(0, 10);
}

export const rubricToText = (rubric) =>
  rubric.map((c) => [c.name, c.points, c.desc, c.teacherOnly ? '교사' : ''].filter((x, i) => i < 3 || x).join(' | ')).join('\n');
